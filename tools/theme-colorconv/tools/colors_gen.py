#!/usr/bin/env python3
"""colors_gen - generate colors.xml from the mapping's scheme definitions.

Usage:
    python3 colors_gen.py <theme-dir> [--mapping mapping.yaml] [--output colors.xml]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from colorconv import miniyaml  # noqa: E402

HEADER = """<?xml version="1.0"?>
<!--
    Generated by theme-colorconv (tools/colors_gen.py).
    Do not edit by hand: change mapping.yaml and regenerate.
    Source theme: {theme}
-->
<theme>
"""

FOOTER = "</theme>\n"


def render(root: Path, mapping_path: Path, output: Path) -> int:
    data = miniyaml.load(str(mapping_path))
    schemes = data.get("schemes") or {}
    if not schemes:
        print("error: no schemes defined in mapping", file=sys.stderr)
        return 1

    parts = [HEADER.format(theme=root.name)]

    for name, block in schemes.items():
        values = (block or {}).get("values") or {}
        parts.append(f'    <colorScheme name="{name}">\n')
        parts.append("        <variables>\n")
        for var, value in values.items():
            parts.append(f"            <{var}>{value}</{var}>\n")
        parts.append("        </variables>\n")
        parts.append("    </colorScheme>\n")

    parts.append(FOOTER)

    output.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {output} with {len(schemes)} color scheme(s): {', '.join(schemes)}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate colors.xml for a theme")
    parser.add_argument("theme")
    parser.add_argument("--mapping", default="mapping.yaml")
    parser.add_argument("--output", default="colors.xml")
    args = parser.parse_args()

    root = Path(args.theme).resolve()
    if not root.is_dir():
        print(f"error: not a directory: {root}", file=sys.stderr)
        return 1

    mapping_path = Path(args.mapping)
    if not mapping_path.is_absolute():
        mapping_path = Path(__file__).resolve().parent.parent / mapping_path

    output = root / args.output
    return render(root, mapping_path, output)


if __name__ == "__main__":
    raise SystemExit(main())
